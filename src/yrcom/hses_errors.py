"""
HSES response-code plaintext lookup (HW1483358 Section 3.4).

The YRC1000 answers every request with a one-byte *status* code and, when the
status is non-zero, an *added-status* word carrying the real reason. Both are
otherwise opaque hex numbers; this module maps them to the descriptions from
the official manual so HsesError messages read like
``... status=0x1F (Vendor-specific error) added=0x2080 (Incorrect mode)``.

Descriptions are kept in English to match the codebase standard and the
Yaskawa manual terminology.
"""

# 4.1 Status-Code (3.4.1)
STATUS_CODES: dict[int, str] = {
    0x00: "Success",
    # 0x01 is not in the 3.4.1 table but is what a live YRC1000 (YAS5.40) returns
    # for almost every rejected/unavailable request — with added-status 0x0000
    # instead of the documented specific codes. Observed for: undefined position
    # variable (P/BP/EX not created), empty file-list filter, missing file,
    # write_file/delete_file in PLAY mode, and move commands in the wrong state
    # (TEACH / servo-off / robot+station together — no 0xB008). Treat as a generic
    # "request not executable in the current state / resource does not exist".
    0x01: "Request not executable in current state / data not present",
    0x08: "Requested command is undefined",
    0x09: "Invalid element number detected",
    0x1F: "Vendor-specific error (see added status)",
    0x28: "Instance of the requested data does not exist in the command",
}

